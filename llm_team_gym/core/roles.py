# Utility helpers (module-private)
# ======================================================================

def _unique_actions(actions: List[Action]) -> List[Action]:
    """De-duplicate actions while preserving order.

    Works with unhashable actions by falling back to an equality scan.
    """
    seen: list = []
    unique: List[Action] = []
    for a in actions:
        # Try fast hash-based membership first.
        try:
            hashable = hash(a)  # noqa: F841 -- only testing hashability
            key: Any = a
        except TypeError:
            key = str(a)

        if key not in seen:
            seen.append(key)
            unique.append(a)
    return unique


def _format_verdicts(verdicts: List[Verdict], highlight_approved: bool) -> str:
    """Render verdicts as a human-readable summary for the thinker prompt."""
    if not verdicts:
        return "(No verdicts received.)"

    lines: List[str] = []
    for v in verdicts:
        status = "APPROVED" if v.approved else "REJECTED"
        marker = " <<" if (highlight_approved and v.approved) else ""
        lines.append(
            f"  [{status}] Action={v.proposal.action} "
            f"(worker={v.proposal.agent_id}, confidence={v.proposal.confidence:.2f}) "
            f"-- Validator {v.validator_id}: {v.reason}{marker}"
        )
    return "\n".join(lines)
