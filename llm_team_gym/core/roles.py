"""
Worker / Validator / Thinker role architecture for LLM-TeamGym.

Implements topology-aware coordination of LLM agent teams following the
three-role paradigm from the PhD thesis on multi-agent coordination:

  Workers   -- propose candidate actions given the game state.
  Validators -- evaluate and approve/reject worker proposals.
  Thinkers  -- integrate validated proposals into a single team action.

The TeamOrchestrator runs one deliberation round:

    Workers propose  -->  Validators validate  -->  Thinker integrates
                                                          |
                                                     final action

Topology constraints are respected: only Worker-Validator pairs that share
an edge in the topology graph interact during the validation phase.

All classes rely exclusively on the standard library (no external deps).
"""

from __future__ import annotations

import enum
import logging
from dataclasses import dataclass, field
from typing import Any, Dict, FrozenSet, List, Optional, Set, Tuple

from llm_team_gym.core.base_agent import BaseAgent
from llm_team_gym.core.base_game import Action, AgentID, Observation

logger = logging.getLogger(__name__)


# ======================================================================
# Role Enum
# ======================================================================

class Role(enum.Enum):
    """The three canonical roles in the Worker/Validator/Thinker paradigm."""

    WORKER = "worker"
    VALIDATOR = "validator"
    THINKER = "thinker"

    def __repr__(self) -> str:
        return f"Role.{self.name}"


# ======================================================================
# Data classes for inter-role messages
# ======================================================================

@dataclass(frozen=True)
class Proposal:
    """A candidate action proposed by a WorkerAgent.

    Attributes
    ----------
    agent_id : AgentID
        The worker that produced this proposal.
    action : Action
        The proposed game action.
    confidence : float
        Self-assessed confidence in [0, 1].
    rationale : str
        Free-text explanation of why this action was chosen.
    """

    agent_id: AgentID
    action: Action
    confidence: float
    rationale: str

    def __post_init__(self) -> None:
        if not (0.0 <= self.confidence <= 1.0):
            raise ValueError(
                f"Proposal confidence must be in [0, 1], got {self.confidence}"
            )


@dataclass(frozen=True)
class Verdict:
    """A validation judgement issued by a ValidatorAgent.

    Attributes
    ----------
    proposal : Proposal
        The proposal being evaluated.
    approved : bool
        Whether the validator endorses this proposal.
    reason : str
        Free-text justification for the decision.
    validator_id : AgentID
        The validator that issued this verdict.
    """

    proposal: Proposal
    approved: bool
    reason: str
    validator_id: AgentID


@dataclass
class RoundResult:
    """Complete record of a single deliberation round.

    Attributes
    ----------
    proposals : list[Proposal]
        All proposals generated by workers.
    verdicts : list[Verdict]
        All verdicts generated by validators.
    final_action : Action
        The action selected by the thinker after integration.
    llm_calls : int
        Total number of ``choose_action`` invocations during the round
        (useful for cost tracking and budgeting).
    """

    proposals: List[Proposal]
    verdicts: List[Verdict]
    final_action: Action
    llm_calls: int


# ======================================================================
# RoleAssignment
# ======================================================================

class RoleAssignment:
    """Maps agent IDs to roles and validates team-composition constraints.

    Two regimes are supported:

    **Standard teams** (>= 3 agents):
        At least one Worker, one Validator, and one Thinker are required.

    **Small teams** (2 agents):
        At least one Worker and one Validator are required.  If no explicit
        Thinker is present the first Validator implicitly doubles as the
        Thinker (the ``implicit_thinker`` property exposes this).

    Parameters
    ----------
    mapping : dict[AgentID, Role]
        Agent-to-role assignment.

    Raises
    ------
    ValueError
        If the mapping violates a composition constraint.
    """

    def __init__(self, mapping: Dict[AgentID, Role]) -> None:
        if not mapping:
            raise ValueError("RoleAssignment requires at least one agent.")
        self._mapping: Dict[AgentID, Role] = dict(mapping)
        self._validate()

    # ---- construction helpers ----------------------------------------

    @classmethod
    def from_lists(
        cls,
        workers: List[AgentID],
        validators: List[AgentID],
        thinkers: Optional[List[AgentID]] = None,
    ) -> "RoleAssignment":
        """Build a RoleAssignment from per-role agent-id lists."""
        mapping: Dict[AgentID, Role] = {}
        for aid in workers:
            mapping[aid] = Role.WORKER
        for aid in validators:
            mapping[aid] = Role.VALIDATOR
        for aid in (thinkers or []):
            mapping[aid] = Role.THINKER
        return cls(mapping)

    # ---- validation --------------------------------------------------

    def _validate(self) -> None:
        workers = self.workers
        validators = self.validators
        thinkers = self.thinkers
        n = len(self._mapping)

        if not workers:
            raise ValueError(
                "RoleAssignment must include at least one WORKER."
            )
        if not validators:
            raise ValueError(
                "RoleAssignment must include at least one VALIDATOR."
            )

        # Standard regime: >= 3 agents require an explicit Thinker.
        if n >= 3 and not thinkers:
            raise ValueError(
                "Teams with 3+ agents must include at least one THINKER. "
                "Assign a THINKER role or reduce the team to 2 agents for "
                "implicit-thinker mode."
            )

    # ---- queries -----------------------------------------------------

    @property
    def workers(self) -> List[AgentID]:
        """Agent IDs assigned to WORKER."""
        return [aid for aid, r in self._mapping.items() if r is Role.WORKER]

    @property
    def validators(self) -> List[AgentID]:
        """Agent IDs assigned to VALIDATOR."""
        return [aid for aid, r in self._mapping.items() if r is Role.VALIDATOR]

    @property
    def thinkers(self) -> List[AgentID]:
        """Agent IDs assigned to THINKER."""
        return [aid for aid, r in self._mapping.items() if r is Role.THINKER]

    @property
    def implicit_thinker(self) -> Optional[AgentID]:
        """Return the implicit thinker for small teams, or ``None``.

        In a 2-agent team with no explicit THINKER the first VALIDATOR
        assumes the thinker responsibility.
        """
        if self.thinkers:
            return None
        return self.validators[0]

    @property
    def effective_thinkers(self) -> List[AgentID]:
        """Thinkers that will actually perform integration (explicit or implicit)."""
        if self.thinkers:
            return list(self.thinkers)
        implicit = self.implicit_thinker
        return [implicit] if implicit is not None else []

    def role_of(self, agent_id: AgentID) -> Role:
        """Return the role assigned to *agent_id*."""
        try:
            return self._mapping[agent_id]
        except KeyError:
            raise KeyError(
                f"Agent '{agent_id}' is not present in this RoleAssignment."
            )

    @property
    def agent_ids(self) -> List[AgentID]:
        """All agent IDs in assignment order."""
        return list(self._mapping.keys())

    def __len__(self) -> int:
        return len(self._mapping)

    def __contains__(self, agent_id: AgentID) -> bool:
        return agent_id in self._mapping

    def __repr__(self) -> str:
        parts = ", ".join(f"{aid}={r.name}" for aid, r in self._mapping.items())
        return f"RoleAssignment({parts})"


# ======================================================================
# Topology
# ======================================================================

class Topology:
    """Undirected graph describing which agents may communicate.

    Edges are stored as frozensets of agent-id pairs.  The primary use-case
    is restricting which Workers a Validator may evaluate (and vice versa).

    If no topology is specified the TeamOrchestrator defaults to
    ``Topology.fully_connected(agent_ids)``.
    """

    def __init__(self, edges: Optional[List[Tuple[AgentID, AgentID]]] = None) -> None:
        self._edges: Set[FrozenSet[AgentID]] = set()
        self._adjacency: Dict[AgentID, Set[AgentID]] = {}
        for u, v in (edges or []):
            self.add_edge(u, v)

    # ---- mutation ----------------------------------------------------

    def add_edge(self, u: AgentID, v: AgentID) -> None:
        """Add an undirected edge between *u* and *v*."""
        edge = frozenset((u, v))
        if edge in self._edges:
            return
        self._edges.add(edge)
        self._adjacency.setdefault(u, set()).add(v)
        self._adjacency.setdefault(v, set()).add(u)

    # ---- queries -----------------------------------------------------

    def connected(self, u: AgentID, v: AgentID) -> bool:
        """Return True if *u* and *v* share an edge."""
        return frozenset((u, v)) in self._edges

    def neighbours(self, agent_id: AgentID) -> List[AgentID]:
        """Return the neighbours of *agent_id*."""
        return sorted(self._adjacency.get(agent_id, set()))

    @property
    def nodes(self) -> List[AgentID]:
        """All nodes that appear in at least one edge."""
        return sorted(self._adjacency.keys())

    # ---- factories ---------------------------------------------------

    @classmethod
    def fully_connected(cls, agent_ids: List[AgentID]) -> "Topology":
        """Return a complete graph over the given agent IDs."""
        edges: List[Tuple[AgentID, AgentID]] = []
        for i, u in enumerate(agent_ids):
            for v in agent_ids[i + 1 :]:
                edges.append((u, v))
        return cls(edges)

    @classmethod
    def bipartite(
        cls, group_a: List[AgentID], group_b: List[AgentID]
    ) -> "Topology":
        """Return a complete bipartite graph (every a connected to every b)."""
        edges = [(a, b) for a in group_a for b in group_b]
        return cls(edges)

    def __repr__(self) -> str:
        edge_strs = [
            f"{sorted(e)}" for e in sorted(self._edges, key=lambda e: sorted(e))
        ]
        return f"Topology({', '.join(edge_strs)})"


