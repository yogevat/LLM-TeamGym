class WorkerAgent(BaseAgent):
    """Wraps any BaseAgent and adds Worker semantics.

    The ``propose`` method calls the inner agent's ``choose_action`` and
    packages the result as a :class:`Proposal`.

    Parameters
    ----------
    inner : BaseAgent
        The agent whose ``choose_action`` provides the actual decision logic.
    default_confidence : float
        Confidence value used when the inner agent does not supply one.
    """

    role: Role = Role.WORKER

    def __init__(
        self,
        inner: BaseAgent,
        default_confidence: float = 0.5,
    ) -> None:
        super().__init__(
            agent_id=inner.agent_id,
            team_id=inner.team_id,
            config=inner.config,
        )
        self._inner = inner
        self._default_confidence = default_confidence

    # ---- core interface ----------------------------------------------

    def choose_action(
        self,
        observation: Observation,
        text_state: str,
        legal_moves: List[Action],
        game_rules: str,
    ) -> Action:
        """Delegate to the inner agent."""
        return self._inner.choose_action(
            observation, text_state, legal_moves, game_rules
        )

    def propose(
        self,
        observation: Observation,
        text_state: str,
        legal_moves: List[Action],
        game_rules: str,
    ) -> Proposal:
        """Generate a Proposal by invoking the inner agent.

        If the inner agent's ``choose_action`` result is a dict with keys
        ``action``, ``confidence``, ``rationale``, those are unpacked.
        Otherwise the raw return value is used as the action with defaults
        for confidence and rationale.
        """
        raw = self._inner.choose_action(
            observation, text_state, legal_moves, game_rules
        )

        # Allow rich responses from LLM-backed agents.
        if isinstance(raw, dict) and "action" in raw:
            action = raw["action"]
            confidence = float(raw.get("confidence", self._default_confidence))
            rationale = str(raw.get("rationale", ""))
        else:
            action = raw
            confidence = self._default_confidence
            rationale = ""

        return Proposal(
            agent_id=self.agent_id,
            action=action,
            confidence=confidence,
            rationale=rationale,
        )

    # ---- lifecycle delegation ----------------------------------------

    def on_episode_start(self, initial_obs: Observation, game_rules: str) -> None:
        self._inner.on_episode_start(initial_obs, game_rules)
        super().on_episode_start(initial_obs, game_rules)

    def on_episode_end(self, final_obs: Observation, total_reward: float) -> None:
        self._inner.on_episode_end(final_obs, total_reward)

    def on_step_end(
        self,
        observation: Observation,
        action: Action,
        reward: float,
        done: bool,
        info: Dict[str, Any],
    ) -> None:
        self._inner.on_step_end(observation, action, reward, done, info)

    @property
    def name(self) -> str:
        return f"WorkerAgent({self._inner.name})"


class ValidatorAgent(BaseAgent):
    """Wraps any BaseAgent and adds Validator semantics.

    The ``validate`` method evaluates a list of :class:`Proposal` objects
    and returns a :class:`Verdict` for each.

    The inner agent's ``choose_action`` is called once per proposal with
    the proposal details injected into the text state.  If the returned
    action (or its string representation) starts with ``"approve"``
    (case-insensitive) the proposal is approved; otherwise it is rejected.
    """

    role: Role = Role.VALIDATOR

    def __init__(self, inner: BaseAgent) -> None:
        super().__init__(
            agent_id=inner.agent_id,
            team_id=inner.team_id,
            config=inner.config,
        )
        self._inner = inner

    # ---- core interface ----------------------------------------------

    def choose_action(
        self,
        observation: Observation,
        text_state: str,
        legal_moves: List[Action],
        game_rules: str,
    ) -> Action:
        """Delegate to the inner agent."""
        return self._inner.choose_action(
            observation, text_state, legal_moves, game_rules
        )

    def validate(
        self,
        proposals: List[Proposal],
        observation: Observation,
        text_state: str,
        game_rules: str,
    ) -> List[Verdict]:
        """Evaluate each proposal and return verdicts.

        For each proposal the inner agent is asked to ``choose_action``
        with the legal moves ``["approve", "reject"]`` and the text state
        augmented with the proposal details.

        If the inner agent returns a dict with keys ``approved`` (bool)
        and ``reason`` (str), those are used directly.  Otherwise the
        raw action is interpreted as a string and matched
        case-insensitively against ``"approve"``.
        """
        verdicts: List[Verdict] = []
        validation_moves: List[Action] = ["approve", "reject"]

        for proposal in proposals:
            augmented_state = (
                f"{text_state}\n\n"
                f"--- PROPOSAL TO VALIDATE ---\n"
                f"Worker: {proposal.agent_id}\n"
                f"Action: {proposal.action}\n"
                f"Confidence: {proposal.confidence:.2f}\n"
                f"Rationale: {proposal.rationale}\n"
                f"----------------------------"
            )

            raw = self._inner.choose_action(
                observation, augmented_state, validation_moves, game_rules
            )

            # Parse rich response dicts from LLM-backed agents.
            if isinstance(raw, dict) and "approved" in raw:
                approved = bool(raw["approved"])
                reason = str(raw.get("reason", ""))
            else:
                action_str = str(raw).strip().lower()
                approved = action_str.startswith("approve")
                reason = str(raw)

            verdicts.append(
                Verdict(
                    proposal=proposal,
                    approved=approved,
                    reason=reason,
                    validator_id=self.agent_id,
                )
            )

        return verdicts

    # ---- lifecycle delegation ----------------------------------------

    def on_episode_start(self, initial_obs: Observation, game_rules: str) -> None:
        self._inner.on_episode_start(initial_obs, game_rules)
        super().on_episode_start(initial_obs, game_rules)

    def on_episode_end(self, final_obs: Observation, total_reward: float) -> None:
        self._inner.on_episode_end(final_obs, total_reward)

    def on_step_end(
        self,
        observation: Observation,
        action: Action,
        reward: float,
        done: bool,
        info: Dict[str, Any],
    ) -> None:
        self._inner.on_step_end(observation, action, reward, done, info)

    @property
    def name(self) -> str:
        return f"ValidatorAgent({self._inner.name})"


class ThinkerAgent(BaseAgent):
    """Wraps any BaseAgent and adds Thinker (readout) semantics.

    The ``integrate`` method receives the full list of verdicts from the
    validation phase and produces a single final :class:`Action`.

    Strategy
    --------
    1. Collect all *approved* proposals.
    2. If at least one proposal is approved the inner agent is asked to
       choose among the approved actions (presented as legal moves).
    3. If no proposal is approved the inner agent is given *all* proposed
       actions as fallback legal moves so the team can still act.
    """

    role: Role = Role.THINKER

    def __init__(self, inner: BaseAgent) -> None:
        super().__init__(
            agent_id=inner.agent_id,
            team_id=inner.team_id,
            config=inner.config,
        )
        self._inner = inner

    # ---- core interface ----------------------------------------------

    def choose_action(
        self,
        observation: Observation,
        text_state: str,
        legal_moves: List[Action],
        game_rules: str,
    ) -> Action:
        """Delegate to the inner agent."""
        return self._inner.choose_action(
            observation, text_state, legal_moves, game_rules
        )

    def integrate(
        self,
        verdicts: List[Verdict],
        observation: Observation,
        text_state: str,
        game_rules: str,
    ) -> Action:
        """Integrate validated proposals into a single team action.

        Returns
        -------
        Action
            The final action selected by the thinker.
        """
        approved = [v for v in verdicts if v.approved]

        if approved:
            candidate_actions = _unique_actions(
                [v.proposal.action for v in approved]
            )
            verdict_summary = _format_verdicts(verdicts, highlight_approved=True)
        else:
            # Fallback: let the thinker pick from all proposals.
            candidate_actions = _unique_actions(
                [v.proposal.action for v in verdicts]
            )
            verdict_summary = _format_verdicts(verdicts, highlight_approved=False)
            logger.warning(
                "No proposals were approved; thinker %s is choosing "
                "among all %d proposed actions as fallback.",
                self.agent_id,
                len(candidate_actions),
            )

        augmented_state = (
            f"{text_state}\n\n"
            f"--- DELIBERATION SUMMARY ---\n"
            f"{verdict_summary}\n"
            f"----------------------------\n"
            f"Select the best action from the candidates above."
        )

        action = self._inner.choose_action(
            observation, augmented_state, candidate_actions, game_rules
        )
        return action

    # ---- lifecycle delegation ----------------------------------------

    def on_episode_start(self, initial_obs: Observation, game_rules: str) -> None:
        self._inner.on_episode_start(initial_obs, game_rules)
        super().on_episode_start(initial_obs, game_rules)

    def on_episode_end(self, final_obs: Observation, total_reward: float) -> None:
        self._inner.on_episode_end(final_obs, total_reward)

    def on_step_end(
        self,
        observation: Observation,
        action: Action,
        reward: float,
        done: bool,
        info: Dict[str, Any],
    ) -> None:
        self._inner.on_step_end(observation, action, reward, done, info)

    @property
    def name(self) -> str:
        return f"ThinkerAgent({self._inner.name})"


