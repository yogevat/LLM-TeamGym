# Team Orchestrator
# ======================================================================

class TeamOrchestrator:
    """Runs a single Worker-Validator-Thinker deliberation round.

    The orchestrator respects the topology graph: a Validator only
    evaluates proposals from Workers to which it is connected.

    Parameters
    ----------
    role_assignment : RoleAssignment
        Defines which agents hold which roles.
    agents : dict[AgentID, BaseAgent]
        Mapping of agent IDs to *role-wrapped* agent instances
        (WorkerAgent, ValidatorAgent, ThinkerAgent).  For small teams
        where the implicit thinker is a ValidatorAgent, the same object
        should appear under the validator key -- the orchestrator handles
        calling ``integrate`` on it by constructing an ad-hoc
        ThinkerAgent wrapper.
    topology : Topology, optional
        Communication graph.  Defaults to fully connected.

    Raises
    ------
    ValueError
        If agent IDs in the role assignment do not match the agents dict,
        or if role types do not match the assigned roles.
    """

    def __init__(
        self,
        role_assignment: RoleAssignment,
        agents: Dict[AgentID, BaseAgent],
        topology: Optional[Topology] = None,
    ) -> None:
        self._assignment = role_assignment
        self._agents = dict(agents)
        self._topology = topology or Topology.fully_connected(
            role_assignment.agent_ids
        )
        self._validate_agents()

    def _validate_agents(self) -> None:
        """Ensure every assigned agent ID has a matching entry in *agents*."""
        missing = set(self._assignment.agent_ids) - set(self._agents.keys())
        if missing:
            raise ValueError(
                f"Agents missing from the agents dict: {sorted(missing)}"
            )

    # ---- public API --------------------------------------------------

    def run_round(
        self,
        observation: Observation,
        text_state: str,
        legal_moves: List[Action],
        game_rules: str,
    ) -> RoundResult:
        """Execute one full deliberation round.

        Steps
        -----
        1. **Propose** -- every Worker generates a Proposal.
        2. **Validate** -- every Validator evaluates proposals from its
           connected Workers (per topology).
        3. **Integrate** -- the Thinker (explicit or implicit) selects
           the final action from the validated proposals.

        Returns
        -------
        RoundResult
            Complete audit trail and the chosen action.
        """
        llm_calls = 0

        # -- Step 1: Workers propose -----------------------------------
        proposals: List[Proposal] = []
        for wid in self._assignment.workers:
            agent = self._agents[wid]
            if isinstance(agent, WorkerAgent):
                proposal = agent.propose(
                    observation, text_state, legal_moves, game_rules
                )
            else:
                # Bare BaseAgent -- wrap on the fly.
                wrapper = WorkerAgent(agent)
                proposal = wrapper.propose(
                    observation, text_state, legal_moves, game_rules
                )
            proposals.append(proposal)
            llm_calls += 1

        logger.debug(
            "Workers produced %d proposal(s): %s",
            len(proposals),
            [p.action for p in proposals],
        )

        # -- Step 2: Validators validate (topology-aware) --------------
        all_verdicts: List[Verdict] = []
        for vid in self._assignment.validators:
            agent = self._agents[vid]

            # Filter proposals to those from connected workers.
            connected_proposals = [
                p
                for p in proposals
                if self._topology.connected(vid, p.agent_id)
            ]

            if not connected_proposals:
                logger.debug(
                    "Validator %s has no connected workers -- skipping.", vid
                )
                continue

            if isinstance(agent, ValidatorAgent):
                verdicts = agent.validate(
                    connected_proposals, observation, text_state, game_rules
                )
            else:
                wrapper = ValidatorAgent(agent)
                verdicts = wrapper.validate(
                    connected_proposals, observation, text_state, game_rules
                )
            all_verdicts.extend(verdicts)
            llm_calls += len(connected_proposals)

        logger.debug(
            "Validators produced %d verdict(s): approved=%d, rejected=%d",
            len(all_verdicts),
            sum(1 for v in all_verdicts if v.approved),
            sum(1 for v in all_verdicts if not v.approved),
        )

        # -- Step 3: Thinker integrates --------------------------------
        thinker_ids = self._assignment.effective_thinkers
        if not thinker_ids:
            raise RuntimeError(
                "No thinker available (explicit or implicit). "
                "Check the RoleAssignment."
            )

        thinker_id = thinker_ids[0]
        thinker_agent = self._agents[thinker_id]

        if isinstance(thinker_agent, ThinkerAgent):
            final_action = thinker_agent.integrate(
                all_verdicts, observation, text_state, game_rules
            )
        else:
            # Implicit thinker (ValidatorAgent doubling) or bare agent.
            wrapper = ThinkerAgent(thinker_agent if not isinstance(thinker_agent, ValidatorAgent) else thinker_agent._inner)
            final_action = wrapper.integrate(
                all_verdicts, observation, text_state, game_rules
            )
        llm_calls += 1

        logger.info(
            "Deliberation round complete: final_action=%s, "
            "proposals=%d, verdicts=%d, llm_calls=%d",
            final_action,
            len(proposals),
            len(all_verdicts),
            llm_calls,
        )

        return RoundResult(
            proposals=proposals,
            verdicts=all_verdicts,
            final_action=final_action,
            llm_calls=llm_calls,
        )


